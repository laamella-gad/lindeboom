## Emits a generated lexer module: the `TokenKind` enum and the DFA as
## `const` tables, driven by `lindeboom/runtime/lexer`.

import std/strutils
import ../runtime/lexer, ../grammar/vocabulary

func nimString(s: string): string =
  ## `s` as a Nim string literal; UTF-8 is kept as is.
  result = "\""
  for c in s:
    case c
    of '"', '\\': result.add '\\' & c
    of '\0' .. '\x1F', '\x7F': result.add "\\x" & toHex(ord(c), 2)
    else: result.add c
  result.add '"'

proc addList(result: var string, items: openArray[string]) =
  ## Comma-separated, wrapped at 80 columns, indented by 4.
  var line = "    "
  for i, x in items:
    let item = x & (if i < items.high: "," else: "")
    if line.len + item.len + 1 > 80 and line.len > 4:
      result.add line.strip(leading = false) & "\n"
      line = "    "
    line.add item & " "
  result.add line.strip(leading = false)

func kindList(v: Vocabulary, kinds: seq[int32]): string =
  ## `kinds` as a Nim `seq[int32]` literal of enum values.
  var items: seq[string]
  for k in kinds: items.add "int32(" & v.tokens[k].ident & ")"
  "@[" & items.join(", ") & "]"

proc genLexerModule*(v: Vocabulary, t: LexerTables, grammarFile: string,
    runtimeImport = "lindeboom/runtime/lexer"): string =
  ## Source of `<name>_lexer.nim`.
  result = "## Generated by lindeboom from " & grammarFile & ". Do not edit.\n\n"
  result.add "import " & runtimeImport & "\n\nexport lexer\n\n"
  result.add "type\n  TokenKind* = enum\n"
  for tok in v.tokens:
    result.add "    " & tok.ident & " = " & nimString(tok.name) & "\n"
  result.add "\n  Token* = LexerToken[TokenKind]\n\n"

  var classes, next, kinds, actions: seq[string]
  for c in t.classes: classes.add $c
  for x in t.next: next.add $x
  for x in t.acceptKind: kinds.add $x
  # the first element sets the literal's type
  classes[0].add "'u8"
  if next.len > 0: next[0].add "'i32"
  if kinds.len > 0: kinds[0].add "'i32"
  for x in t.acceptAction: actions.add $x
  result.add "const lexerTables = LexerTables(\n"
  result.add "  classes: [\n"
  result.addList classes
  result.add "],\n  classCount: " & $t.classCount & ",\n"
  result.add "  next: @[\n"
  result.addList next
  result.add "],\n  acceptKind: @[\n"
  result.addList kinds
  result.add "],\n  acceptAction: @[\n"
  result.addList actions
  result.add "]"
  let ind = t.indentation
  if ind.enabled:
    result.add ",\n  indentation: IndentConfig(enabled: true,\n"
    result.add "    newline: int32(" & v.tokens[ind.newline].ident & "), indent: int32(" &
      v.tokens[ind.indent].ident & "), dedent: int32(" & v.tokens[ind.dedent].ident & "),\n"
    result.add "    opens: " & v.kindList(ind.opens) & ",\n    closes: " & v.kindList(ind.closes) & ",\n"
    result.add "    tabs: tm" & capitalizeAscii($ind.tabs) & ", tabWidth: " & $ind.tabWidth & ")"
  result.add ")\n\n"
  result.add """
proc tokenize*(src: string, d: var Diagnostics): seq[Token] =
  ## Splits `src` into tokens, ending with `tkEOF`. Skips characters that
  ## cannot start a token, reporting each run of them.
  tokenize[TokenKind](lexerTables, src, d)
